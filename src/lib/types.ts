export type Spec = 'Budget' | 'Standard' | 'Premium'

export interface Rates {
  vat: number
  /** Inflation since the rates were last checked; compounds with the regional multiplier. */
  inflation: number
  benchmarks: Record<string, Record<Spec, [number, number]>>
  regions: Record<string, number>
  roofs: Record<string, [number, number]>
}

export interface QuoteInput {
  job: string
  spec: Spec
  area: number
  region: string
  roof: string
}

export interface QuoteResult {
  exLow: number
  exHigh: number
  incLow: number
  incHigh: number
  midpoint: number
  perM2IncLow: number
  perM2IncHigh: number
}

export interface LibraryItem {
  category: 'Labour' | 'Material' | 'Waste'
  item: string
  unit: string
  rate: number
  low: number
  high: number
  source: string
}

/** Shape of src/data/rate-library.json (generated by scripts/export-rate-library.py). */
export interface RateLibrary {
  source: string
  items: LibraryItem[]
  benchmarks: Record<string, Record<Spec, [number, number]> & { notes: string }>
  fees: { item: string; low: number; high: number; unit: string; source: string }[]
  roofs: Record<string, [number, number]>
  roofCoverings: Record<string, { low: number; high: number; notes: string }>
  plantHire: { item: string; day: number; week: number; notes: string | null }[]
}
